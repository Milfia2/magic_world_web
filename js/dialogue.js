export function dialogueFor(speaker, player, scene, topic = 'scene', random = Math.random) {
  if (speaker === player) return line('你停下來整理了一下手邊的東西。','先把這件事做完，再去找大家吧。');
  if (topic === 'gift') return gifts[speaker];
  if (topics[topic]?.[speaker]) return topics[topic][speaker];
  if (topic === 'friends') return relations[speaker]?.[player] || line('', '走吧，大家應該就在附近。');
  const key = scene.startsWith('room/') ? 'room' : scene;
  const context = scenes[speaker]?.[key];
  const pair = relations[speaker]?.[player];
  if (context && (random() < .72 || !pair)) return context;
  return pair || context || Object.values(scenes[speaker] || {})[0];
}
